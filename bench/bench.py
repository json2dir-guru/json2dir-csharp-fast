#!/usr/bin/env python3
"""Tiny local benchmark: the three workloads of the json2dir benchmark suite's quick set.

    python3 bench/bench.py [-n RUNS] [--storage disk|tmpfs|both] NAME=COMMAND ...

Workloads (as generated by json2dir-tester's BenchFixtures):
  empty         {}
  files-1000    1000 files f00000..f00999, 64 random lowercase letters each
  payload-8MiB  one file "payload" with 8 MiB of 'x'

Every invocation is a fresh process run through /bin/sh in an empty target directory; the document
arrives through a pipe written by this script (like the benchmark harness), or with --stdin file
redirected from the input file. Reports the median wall time in ms (3 warmups, then -n runs) and the maximum RSS
(GNU time, 3 separate runs) per implementation, workload and storage.
"""
import argparse
import json
import os
import random
import shutil
import statistics
import subprocess
import tempfile
import time

WORKLOADS = ["empty", "files-1000", "payload-8MiB"]
STORAGE = {"disk": "/tmp", "tmpfs": "/dev/shm"}


def generate(directory):
    rnd = random.Random(1)
    docs = {
        "empty": {},
        "files-1000": {f"f{i:05d}": "".join(chr(rnd.randrange(97, 123)) for _ in range(64)) for i in range(1000)},
        "payload-8MiB": {"payload": "x" * (8 * 1048576)},
    }
    paths = {}
    for name, doc in docs.items():
        paths[name] = os.path.join(directory, name + ".json")
        with open(paths[name], "w") as f:
            json.dump(doc, f, separators=(",", ":"))
    return paths


def run_once(command, input_path, target, rss=False, pipe=True):
    """Wall time in ms of one run; with rss=True, the maximum RSS in KiB measured by GNU time instead
    (a forked Python child would report Python's own RSS)."""
    os.mkdir(target)
    argv = ["/bin/sh", "-c", command]
    if rss:
        argv = ["/usr/bin/time", "-f", "%M", "-o", target + ".rss"] + argv
    if pipe:
        # Like the benchmark harness: the document arrives through a pipe written by the parent.
        with open(input_path, "rb") as f:
            data = f.read()
        start = time.perf_counter()
        proc = subprocess.run(argv, input=data, cwd=target, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
        elapsed = time.perf_counter() - start
    else:
        with open(input_path, "rb") as stdin:
            start = time.perf_counter()
            proc = subprocess.run(argv, stdin=stdin, cwd=target, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
            elapsed = time.perf_counter() - start
    shutil.rmtree(target)
    if proc.returncode != 0:
        raise SystemExit(f"{command!r} failed ({proc.returncode}): {proc.stderr.decode(errors='replace')}")
    if rss:
        with open(target + ".rss") as f:
            value = int(f.read().split()[-1])
        os.remove(target + ".rss")
        return value
    return elapsed * 1000


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-n", type=int, default=15, help="timed runs per cell (after 3 warmups)")
    ap.add_argument("--storage", default="both", choices=["disk", "tmpfs", "both"])
    ap.add_argument("--workload", action="append", choices=WORKLOADS)
    ap.add_argument("--stdin", default="pipe", choices=["pipe", "file"],
                    help="feed the document through a pipe (as the benchmark harness does) or redirect a file")
    ap.add_argument("impls", nargs="+", metavar="NAME=COMMAND")
    args = ap.parse_args()
    impls = [tuple(s.split("=", 1)) for s in args.impls]
    storages = ["disk", "tmpfs"] if args.storage == "both" else [args.storage]
    workloads = args.workload or WORKLOADS

    with tempfile.TemporaryDirectory(prefix="j2d-bench-in-") as tmp:
        inputs = generate(tmp)
        rows = []
        for storage in storages:
            base = tempfile.mkdtemp(prefix="j2d-bench-", dir=STORAGE[storage])
            try:
                for workload in workloads:
                    for name, command in impls:
                        target = os.path.join(base, "t")
                        pipe = args.stdin == "pipe"
                        samples = [run_once(command, inputs[workload], target, pipe=pipe) for _ in range(3 + args.n)][3:]
                        rss = max(run_once(command, inputs[workload], target, rss=True, pipe=pipe) for _ in range(3))
                        rows.append((storage, workload, name, statistics.median(samples), min(samples), rss))
                        print(f"{storage:5} {workload:13} {name:16} median {statistics.median(samples):7.2f} ms"
                              f"  min {min(samples):7.2f}  rss {rss / 1024:6.1f} MiB", flush=True)
            finally:
                shutil.rmtree(base, ignore_errors=True)

    print()
    print("| storage | workload | " + " | ".join(n for n, _ in impls) + " |")
    print("|---|---|" + "---|" * len(impls))
    for storage in storages:
        for workload in workloads:
            cells = {r[2]: r for r in rows if r[0] == storage and r[1] == workload}
            print(f"| {storage} | {workload} | " + " | ".join(
                f"{cells[n][3]:.1f} ms / {cells[n][5] / 1024:.0f} MiB" for n, _ in impls) + " |")


if __name__ == "__main__":
    main()
